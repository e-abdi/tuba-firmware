/*
 * app_time.c — Software UTC wall clock (no RTC hardware)
 *
 * See app_time.h for the design. Implementation notes:
 *
 *  - The clock is stored as a Unix-epoch "base" plus the uptime at which
 *    that base was set. Reading the clock is base + elapsed uptime.
 *  - Calendar conversion uses Howard Hinnant's days-from-civil /
 *    civil-from-days algorithms so we do not depend on libc time functions
 *    (minimal libc configurations may not provide timegm/gmtime_r).
 *  - A spinlock protects the (base, anchor) pair so a GPS re-sync from the
 *    deploy worker thread cannot tear a concurrent read from another thread.
 */
#include <zephyr/kernel.h>
#include <zephyr/spinlock.h>
#include <stdio.h>
#include <stdlib.h>
#include <errno.h>

#include "app_time.h"
#include "app_print.h"
#include "version.h"   /* BUILD_DATE "YYYY-MM-DD hh:mm:ss" */

static struct k_spinlock time_lock;
static int64_t base_epoch_s;      /* Unix seconds at the anchor point */
static int64_t base_uptime_ms;    /* k_uptime_get() at the anchor point */
static int64_t build_epoch_s;     /* firmware build date, used as sanity floor */
static app_time_source_t source = APP_TIME_SRC_NONE;

/* ---- Calendar math (proleptic Gregorian, no libc) ------------------- */

/* Days since 1970-01-01 for a civil date. Valid for all practical years.
 * Algorithm: Howard Hinnant, "chrono-Compatible Low-Level Date Algorithms". */
static int64_t days_from_civil(int y, int m, int d)
{
    y -= m <= 2;
    const int64_t era = (y >= 0 ? y : y - 399) / 400;
    const unsigned yoe = (unsigned)(y - era * 400);                     /* [0, 399] */
    const unsigned doy = (153u * (unsigned)(m + (m > 2 ? -3 : 9)) + 2u) / 5u
                         + (unsigned)d - 1u;                            /* [0, 365] */
    const unsigned doe = yoe * 365u + yoe / 4u - yoe / 100u + doy;      /* [0, 146096] */
    return era * 146097 + (int64_t)doe - 719468;
}

/* Inverse of days_from_civil: civil date from days since 1970-01-01. */
static void civil_from_days(int64_t z, int *y_out, int *m_out, int *d_out)
{
    z += 719468;
    const int64_t era = (z >= 0 ? z : z - 146096) / 146097;
    const unsigned doe = (unsigned)(z - era * 146097);                  /* [0, 146096] */
    const unsigned yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
    const int64_t y = (int64_t)yoe + era * 400;
    const unsigned doy = doe - (365u * yoe + yoe / 4u - yoe / 100u);    /* [0, 365] */
    const unsigned mp = (5u * doy + 2u) / 153u;                        /* [0, 11] */
    const unsigned d = doy - (153u * mp + 2u) / 5u + 1u;               /* [1, 31] */
    const unsigned m = mp + (mp < 10 ? 3 : -9);                        /* [1, 12] */
    *y_out = (int)(y + (m <= 2));
    *m_out = (int)m;
    *d_out = (int)d;
}

/* Convert civil date+time (UTC) to Unix seconds. Returns -1 on invalid input. */
static int64_t to_epoch(int year, int month, int day, int hour, int min, int sec)
{
    if (month < 1 || month > 12 || day < 1 || day > 31 ||
        hour < 0 || hour > 23 || min < 0 || min > 59 || sec < 0 || sec > 60) {
        return -1;
    }
    return days_from_civil(year, month, day) * 86400LL
           + hour * 3600LL + min * 60LL + sec;
}

/* ---- Anchor management ---------------------------------------------- */

/* Set the clock: "right now, the wall time is epoch_s". */
static void set_anchor(int64_t epoch_s, app_time_source_t src)
{
    k_spinlock_key_t key = k_spin_lock(&time_lock);
    base_epoch_s = epoch_s;
    base_uptime_ms = k_uptime_get();
    source = src;
    k_spin_unlock(&time_lock, key);
}

int64_t app_time_now(void)
{
    k_spinlock_key_t key = k_spin_lock(&time_lock);
    int64_t now = base_epoch_s + (k_uptime_get() - base_uptime_ms) / 1000;
    k_spin_unlock(&time_lock, key);
    return now;
}

/* ---- Public API ------------------------------------------------------ */

void app_time_init(void)
{
    /* BUILD_DATE is generated by gen_version.sh as "YYYY-MM-DD hh:mm:ss".
     * Parse it by hand (fixed layout) to avoid a sscanf dependency. */
    const char *s = BUILD_DATE;
    int year = atoi(s);          /* chars 0-3  */
    int mon  = atoi(s + 5);      /* chars 5-6  */
    int day  = atoi(s + 8);      /* chars 8-9  */
    int hour = atoi(s + 11);     /* chars 11-12 */
    int min  = atoi(s + 14);     /* chars 14-15 */
    int sec  = atoi(s + 17);     /* chars 17-18 */

    int64_t epoch = to_epoch(year, mon, day, hour, min, sec);
    if (epoch < 0) {
        /* Malformed build date string — fall back to epoch 0 but keep going. */
        app_printk("[TIME] WARNING: could not parse BUILD_DATE '%s'\r\n", s);
        epoch = 0;
    }
    build_epoch_s = epoch;
    set_anchor(epoch, APP_TIME_SRC_BUILD);

    char buf[APP_TIME_STR_LEN];
    app_printk("[TIME] clock set from build date: %s (will re-sync on GPS fix)\r\n",
               app_time_str(buf, sizeof(buf)));
}

int app_time_set_from_gps(int hour, int min, int sec,
                          int day, int month, int year2)
{
    /* NMEA gives a two-digit year; the glider will not outlive 2099. */
    int year = 2000 + year2;
    int64_t epoch = to_epoch(year, month, day, hour, min, sec);
    if (epoch < 0) {
        return -EINVAL;
    }

    /* Never accept a GPS time earlier than the firmware build — that means
     * the receiver has not decoded a valid date yet (cold-start garbage). */
    if (epoch < build_epoch_s) {
        return -EINVAL;
    }

    int64_t old_now = app_time_now();
    set_anchor(epoch, APP_TIME_SRC_GPS);

    /* Only announce noticeable corrections to keep mission logs clean. */
    int64_t delta = epoch - old_now;
    if (delta > 2 || delta < -2) {
        char buf[APP_TIME_STR_LEN];
        app_printk("[TIME] synced from GPS: %s UTC (adjusted %lld s)\r\n",
                   app_time_str(buf, sizeof(buf)), (long long)delta);
    }
    return 0;
}

const char *app_time_str(char *buf, size_t buflen)
{
    int64_t now = app_time_now();
    int64_t days = now / 86400;
    int64_t rem = now % 86400;
    if (rem < 0) { rem += 86400; days -= 1; }  /* handle pre-1970 gracefully */

    int y, m, d;
    civil_from_days(days, &y, &m, &d);
    snprintf(buf, buflen, "%04d-%02d-%02d %02d:%02d:%02d",
             y, m, d,
             (int)(rem / 3600), (int)((rem / 60) % 60), (int)(rem % 60));
    return buf;
}

app_time_source_t app_time_source(void)
{
    return source;
}

const char *app_time_source_str(void)
{
    switch (source) {
    case APP_TIME_SRC_BUILD: return "build";
    case APP_TIME_SRC_GPS:   return "GPS";
    default:                 return "none";
    }
}
